import { initializeApp } from 'firebase/app'
import { CustomProvider, initializeAppCheck, ReCaptchaEnterpriseProvider } from 'firebase/app-check'
import { createUserWithEmailAndPassword, getAuth, signInWithEmailAndPassword, signOut } from 'firebase/auth'
import { collection, doc, getDoc, getDocs, getFirestore, query, setDoc, where } from 'firebase/firestore'

const config = {
  apiKey: import.meta.env.VITE_FIREBASE_API_KEY,
  authDomain: import.meta.env.VITE_FIREBASE_AUTH_DOMAIN,
  projectId: import.meta.env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: import.meta.env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: import.meta.env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: import.meta.env.VITE_FIREBASE_APP_ID,
}

export const firebaseConfigured = Object.values(config).every(Boolean)
export const app = firebaseConfigured ? initializeApp(config) : null

const isLocalhost = typeof window !== 'undefined'
  && ['localhost', '127.0.0.1', '::1', '[::1]'].includes(window.location.hostname)
const appCheckSiteKey = import.meta.env.VITE_FIREBASE_APPCHECK_RECAPTCHA_SITE_KEY
const isLocalDevelopment = import.meta.env.DEV && isLocalhost

if (app && isLocalDevelopment) {
  self.FIREBASE_APPCHECK_DEBUG_TOKEN = true
  initializeAppCheck(app, {
    // Debug mode uses the token generated by Firebase; the custom provider is
    // never called for the debug exchange and avoids requiring a site key.
    provider: new CustomProvider({
      getToken: async () => ({ token: '', expireTimeMillis: Date.now() + 3600000 }),
    }),
    isTokenAutoRefreshEnabled: true,
  })
  console.info('[YaadSaathi] Firebase App Check initialized in localhost debug mode')
} else if (app) {
  if (!appCheckSiteKey) {
    throw new Error('VITE_FIREBASE_APPCHECK_RECAPTCHA_SITE_KEY is required outside localhost development')
  }
  initializeAppCheck(app, {
    provider: new ReCaptchaEnterpriseProvider(appCheckSiteKey),
    isTokenAutoRefreshEnabled: true,
  })
}

export const firebaseAuth = app ? getAuth(app) : null
export const firestore = app ? getFirestore(app) : null

export async function firebaseLogin(email, password) {
  if (!firebaseAuth) return null
  const result = await signInWithEmailAndPassword(firebaseAuth, email, password)
  return result.user
}

export async function firebaseProfile(uid) {
  if (!firestore) return null
  const snapshot = await getDoc(doc(firestore, 'users', uid))
  return snapshot.exists() ? snapshot.data() : null
}

export async function firebaseRegister(profile) {
  if (!firebaseAuth || !firestore) return null
  const result = await createUserWithEmailAndPassword(firebaseAuth, profile.email, profile.password)
  const now = new Date().toISOString()
  await setDoc(doc(firestore, 'users', result.user.uid), {
    uid: result.user.uid,
    name: profile.fullName,
    age: Number(profile.age),
    phone: profile.mobile,
    email: profile.email,
    location: profile.location,
    role: profile.role,
    relationship: profile.relationship || '',
    specialization: profile.specialization || '',
    textLanguage: profile.textLang,
    voiceLanguage: profile.voiceLang,
    caregiverId: profile.caregiverId || null,
    createdAt: now,
    updatedAt: now,
  })
  return result.user
}

export async function firebaseLogout() {
  if (firebaseAuth) await signOut(firebaseAuth)
}

export async function firebaseRelationships(user) {
  if (!firestore || !user?.id) return []
  const field = user.role === 'patient' ? 'patientId' : user.role === 'caregiver' ? 'caregiverId' : 'doctorId'
  const snapshot = await getDocs(query(collection(firestore, 'relationships'), where(field, '==', user.id)))
  return snapshot.docs.map((item) => ({ id: item.id, ...item.data() }))
}

export async function firebasePatientRecords(patientId) {
  if (!firestore || !patientId) return { sessions: [], tasks: [], reminders: [], settings: [] }
  const read = async (name) => {
    const snapshot = await getDocs(query(collection(firestore, name), where('patientId', '==', patientId)))
    return snapshot.docs.map((item) => ({ id: item.id, ...item.data() }))
  }
  const [sessions, tasks, reminders, settings] = await Promise.all([
    read('gameSessions'),
    read('dailyTasks'),
    read('reminders'),
    read('settings'),
  ])
  return { sessions, tasks, reminders, settings }
}

export async function uploadFirestoreRecord(record) {
  if (!firestore) return false
  const payload = record.payload?.payload || record.payload || {}
  const kind = record.payload?.kind
  const collection = kind === 'gameSession'
    ? 'gameSessions'
    : record.payload?.kind === 'dailyTask'
      ? 'dailyTasks'
      : record.payload?.kind === 'relationship'
        ? 'relationships'
        : kind === 'story_recall'
          ? 'gameSessions'
          : kind === 'reminder' || kind === 'reminderDeleted'
            ? 'reminders'
            : kind === 'dailyTaskDeleted'
              ? 'dailyTasks'
                : kind === 'settings'
                  ? 'settings'
            : 'telemetry'
  await setDoc(doc(firestore, collection, payload.id || record.id), payload, { merge: true })
  return true
}
